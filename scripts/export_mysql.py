#!/usr/bin/env python3
"""
Meenakshi Build World — export tile_marketplace.sqlite as a MySQL/MariaDB dump.

The catalogue is built locally in SQLite (scripts/import_somany_products.py);
this turns that database into a single .sql file for hosts that only offer
MySQL, e.g. Hostinger (import it in phpMyAdmin -> Import).

Writes database/meenakshi_mysql.sql (and a .sql.gz copy for upload limits):

  * one CREATE TABLE per SQLite table, with types mapped to MySQL
    (INTEGER -> INT, REAL -> DOUBLE, short/indexed TEXT -> VARCHAR(255)),
    the same primary keys, unique keys, indexes and foreign keys
    (ON DELETE CASCADE / SET NULL), InnoDB + utf8mb4;
  * every row as batched multi-row INSERTs, ids preserved, AUTO_INCREMENT
    continuing after the highest id.

The full dump drops and recreates every table — use it for the first import.
For later catalogue updates use --catalog-only: it writes
database/meenakshi_catalog_mysql.sql with just the product/category tables,
so orders, inquiries, users, blogs and settings on the live site are kept.

  python3 scripts/export_mysql.py                  # full database
  python3 scripts/export_mysql.py --catalog-only   # products + taxonomy only
"""
import gzip, os, re, sqlite3, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DB_PATH = os.path.join(ROOT, 'tile_marketplace.sqlite')
OUT_DIR = os.path.join(ROOT, 'database')
CATALOG_ONLY = '--catalog-only' in sys.argv[1:]
OUT_PATH = os.path.join(OUT_DIR, 'meenakshi_catalog_mysql.sql' if CATALOG_ONLY else 'meenakshi_mysql.sql')
# Tables rebuilt by scripts/import_somany_products.py (everything else is live-site data).
CATALOG_TABLES = {'products', 'product_images', 'product_variants', 'inventory', 'product_categories',
                  'product_attributes', 'categories', 'category_groups', 'category_attributes',
                  'attribute_values', 'brands', 'collections'}
BATCH = 500


def q(name):
    return '`' + name.replace('`', '``') + '`'


def lit(v):
    if v is None:
        return 'NULL'
    if isinstance(v, bool):
        return '1' if v else '0'
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v) if v == v and v not in (float('inf'), float('-inf')) else 'NULL'
    if isinstance(v, bytes):
        return "X'" + v.hex() + "'" if v else "''"
    s = str(v)
    s = (s.replace('\\', '\\\\').replace("'", "\\'").replace('\0', '\\0')
          .replace('\n', '\\n').replace('\r', '\\r').replace('\x1a', '\\Z'))
    return "'" + s + "'"


def default_sql(dflt, mysql_type):
    """SQLite dflt_value (SQL text) -> MySQL DEFAULT clause."""
    if dflt is None:
        return ''
    d = dflt.strip()
    if d.upper() == 'CURRENT_TIMESTAMP':
        return ' DEFAULT CURRENT_TIMESTAMP' if mysql_type == 'DATETIME' else ''
    if d.upper() == 'NULL':
        return ' DEFAULT NULL'
    if re.fullmatch(r'\(?-?\d+(\.\d+)?\)?', d):
        return ' DEFAULT ' + d.strip('()')
    m = re.fullmatch(r"'(.*)'", d, re.S)
    if m:
        val = lit(m.group(1).replace("''", "'"))
        # TEXT columns only accept expression defaults: DEFAULT ('x').
        return f' DEFAULT ({val})' if mysql_type in ('TEXT', 'MEDIUMTEXT') else f' DEFAULT {val}'
    return ''


def main():
    con = sqlite3.connect(DB_PATH)
    has_seq = con.execute("SELECT 1 FROM sqlite_master WHERE name = 'sqlite_sequence'").fetchone() is not None
    tables = [r[0] for r in con.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name")]
    if CATALOG_ONLY:
        tables = [t for t in tables if t in CATALOG_TABLES]

    os.makedirs(OUT_DIR, exist_ok=True)
    out = open(OUT_PATH, 'w', encoding='utf-8', newline='\n')
    w = out.write
    w('-- Meenakshi Build World — MySQL/MariaDB dump generated by scripts/export_mysql.py\n')
    w('-- Catalogue tables only: orders, inquiries, users, blogs and settings are left untouched.\n\n'
      if CATALOG_ONLY else '-- Full database: replaces every table. Import via phpMyAdmin -> Import.\n\n')
    w("SET NAMES utf8mb4;\nSET FOREIGN_KEY_CHECKS = 0;\nSET UNIQUE_CHECKS = 0;\n")
    w("SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';\nSET time_zone = '+00:00';\n\n")

    summary = []
    for t in tables:
        cols = con.execute(f'PRAGMA table_info({q(t)})').fetchall()      # cid,name,type,notnull,dflt,pk
        fks = con.execute(f'PRAGMA foreign_key_list({q(t)})').fetchall()  # id,seq,table,from,to,on_update,on_delete,match
        idx = []
        for _, iname, unique, origin, _p in con.execute(f'PRAGMA index_list({q(t)})').fetchall():
            icols = [r[2] for r in con.execute(f'PRAGMA index_info({q(iname)})')]
            if origin == 'pk':
                continue
            idx.append((iname, bool(unique), icols))
        keyed = {c for _, _, ic in idx for c in ic} | {fk[3] for fk in fks}
        pk_cols = [c[1] for c in sorted(cols, key=lambda c: c[5]) if c[5]]

        defs = []
        for _, name, ctype, notnull, dflt, pk in cols:
            base = (ctype or '').upper()
            if 'INT' in base:
                mt = 'INT'
            elif any(k in base for k in ('REAL', 'FLOA', 'DOUB', 'NUMERIC', 'DECIMAL')):
                mt = 'DOUBLE'
            elif 'DATE' in base or 'TIME' in base:
                mt = 'DATETIME'
            elif 'BLOB' in base:
                mt = 'LONGBLOB'
            else:
                maxlen = con.execute(f'SELECT MAX(LENGTH(CAST({q(name)} AS BLOB))) FROM {q(t)}').fetchone()[0] or 0
                if (name in keyed or pk or dflt is not None) and maxlen <= 255:
                    mt = 'VARCHAR(255)'
                elif maxlen > 60000:
                    mt = 'MEDIUMTEXT'
                else:
                    mt = 'TEXT'
            line = f'  {q(name)} {mt}'
            if notnull or pk:
                line += ' NOT NULL'
            if pk and len(pk_cols) == 1 and mt == 'INT':
                line += ' AUTO_INCREMENT'
            else:
                line += default_sql(dflt, mt)
            defs.append(line)
        if pk_cols:
            defs.append('  PRIMARY KEY (' + ', '.join(q(c) for c in pk_cols) + ')')
        for iname, unique, icols in idx:
            name = iname if not iname.startswith('sqlite_autoindex') else f'uq_{t}_' + '_'.join(icols)
            defs.append(f"  {'UNIQUE KEY' if unique else 'KEY'} {q(name[:64])} (" + ', '.join(q(c) for c in icols) + ')')
        for fk in sorted(fks, key=lambda f: (f[0], f[1])):
            _id, _seq, rt, frm, to, _upd, on_del, _match = fk
            act = f' ON DELETE {on_del}' if on_del and on_del != 'NO ACTION' else ''
            defs.append(f'  CONSTRAINT {q(f"fk_{t}_{frm}"[:64])} FOREIGN KEY ({q(frm)}) REFERENCES {q(rt)} ({q(to or "id")}){act}')

        n = con.execute(f'SELECT COUNT(*) FROM {q(t)}').fetchone()[0]
        nxt = 1
        if len(pk_cols) == 1:
            # Continue SQLite's AUTOINCREMENT counter so deleted ids are never reused.
            top = con.execute(f'SELECT MAX({q(pk_cols[0])}) FROM {q(t)}').fetchone()[0] or 0
            seq = con.execute('SELECT seq FROM sqlite_sequence WHERE name = ?', (t,)).fetchone() if has_seq else None
            nxt = max(top, seq[0] if seq else 0) + 1
        w(f'DROP TABLE IF EXISTS {q(t)};\n')
        w(f'CREATE TABLE {q(t)} (\n' + ',\n'.join(defs) +
          f'\n) ENGINE=InnoDB AUTO_INCREMENT={nxt} DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;\n\n')

        names = [c[1] for c in cols]
        col_list = ', '.join(q(c) for c in names)
        cur = con.execute(f'SELECT {", ".join(q(c) for c in names)} FROM {q(t)} ORDER BY rowid')
        while True:
            rows = cur.fetchmany(BATCH)
            if not rows:
                break
            w(f'INSERT INTO {q(t)} ({col_list}) VALUES\n' +
              ',\n'.join('(' + ','.join(lit(v) for v in r) + ')' for r in rows) + ';\n')
        w('\n')
        summary.append((t, n))

    w('SET UNIQUE_CHECKS = 1;\nSET FOREIGN_KEY_CHECKS = 1;\n')
    out.close()

    with open(OUT_PATH, 'rb') as f, gzip.open(OUT_PATH + '.gz', 'wb', compresslevel=9) as g:
        g.write(f.read())
    print(f'Wrote {os.path.relpath(OUT_PATH, ROOT)} ({os.path.getsize(OUT_PATH) / 1e6:.1f} MB) and .gz '
          f'({os.path.getsize(OUT_PATH + ".gz") / 1e6:.1f} MB)')
    for t, n in summary:
        print(f'  {t:24} {n:>7} rows')


if __name__ == '__main__':
    main()
